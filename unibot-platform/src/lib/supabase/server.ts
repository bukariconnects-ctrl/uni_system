/**
 * Creates a true service-role Supabase client that fully bypasses RLS.
 * Unlike createAdminClient (which uses @supabase/ssr and may still apply
 * user JWT from cookies), this client uses the raw supabase-js client
 * with service_role key, so RLS is completely skipped.
 * Use ONLY in server-side code after verifying user permissions separately.
 */
export function createServiceClient() {
  return createSupabaseClient(
    process.env.NEXT_PUBLIC_SUPABASE_URL!,
    process.env.SUPABASE_SERVICE_ROLE_KEY!,
    {
      auth: {
        autoRefreshToken: false,
        persistSession: false,
      },
    }
  );
}
